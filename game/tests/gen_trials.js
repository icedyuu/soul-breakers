// Builds the COMBO TRIALS data (src/09l_trials_data.js) from bot-verified combos.
//   node gen_trials.js [ids]   — uses the bot runSeq from combofind.js
// Per fighter 5 trials, easy → hard: BASICS (L M H), EASY (special finish), MEDIUM (full chain),
// HARD (launcher / follow-up route), SOUL (ultimate finish). Candidates: ../tools/trial_picks.json
// (hand-picked earlier), else generated like combofind. A trial is only kept when the bot lands it
// in 3 of 3 runs (random parts: cards, dice…) at normal speed and with 2 frames delay.
const { open } = require('./harness');
const fs = require('fs'), path = require('path');
(async () => {
  const { browser, page, errors } = await open();
  const src = fs.readFileSync(path.join(__dirname, 'combofind.js'), 'utf8');
  await page.evaluate(src.slice(src.indexOf('window.runSeq'), src.indexOf('  });\n  await page.evaluate(a =>')));
  await page.evaluate(() => window.APPROACH = 70);
  const picks = JSON.parse(fs.readFileSync(path.join(__dirname, '../tools/trial_picks.json'), 'utf8'));
  const ids = process.argv[2] ? process.argv[2].split(',') : await page.evaluate(() => CHARS.map(c => c.id));
  const outFile = path.join(__dirname, '../src/09l_trials_data.js');
  let out = {};
  try { out = JSON.parse(fs.readFileSync(outFile, 'utf8').replace(/^[^{]*/, '').replace(/;\s*$/, '')); } catch (e) { }
  const test = async (id, seq) => {
    let ok = 0, dmg = 0, hits = 0;
    for (let r = 0; r < 3; r++) { const x = await page.evaluate(([id, s, d]) => runSeq(id, 'kazuma', s, d), [id, seq, r === 2 ? 2 : 0]); if (x.ok) { ok++; dmg = Math.max(dmg, x.dmg); hits = Math.max(hits, x.hits); } }
    return { ok: ok === 3, dmg, hits };
  };
  for (const id of ids) {
    const M = await page.evaluate(id => { const ch = CHARS.find(c => c.id === id), o = {}; for (const [k, m] of Object.entries(ch.moves)) o[k] = { ult: !!m.ult, special: !!m.special, fu: (m.followups || []).map(f => f.move), counter: !!m.counter }; return o; }, id);
    const has = k => !!M[k], P = Object.fromEntries((picks[id] || []).map(([l, s]) => [l, s]));
    const specials = ['sp1', 'sp1f', 'sp2', 'sp2f', 'sp2d'].filter(has);
    const fuOf = k => (M[k] ? M[k].fu : []).filter(has);
    const cand = { BASICS: [['L', 'M', 'H']], EASY: [], MEDIUM: [], HARD: [], SOUL: [] };
    if (P.Einstieg) cand.EASY.push(P.Einstieg);
    if (P['Volle Kette']) cand.MEDIUM.push(P['Volle Kette']);
    if (P.Spezial) cand.HARD.push(P.Spezial);
    if (P.Soul) cand.SOUL.push(P.Soul);
    for (const sp of specials) {
      cand.EASY.push(['L', 'M', 'H', sp]);
      for (const f of fuOf(sp)) cand.MEDIUM.push(['L', 'L', 'M', 'H', sp, f], ['L', 'M', 'H', sp, f]);
      cand.MEDIUM.push(['L', 'L', 'L', 'M', 'H', sp], ['L', 'L', 'M', 'H', sp]);
      if (has('ult')) cand.SOUL.push(['L', 'L', 'M', 'H', sp, 'ult'], ['M', 'H', sp, 'ult'], ['L', 'M', 'H', sp, 'ult']);
    }
    if (has('LH')) cand.HARD.push(['L', 'M', 'LH', 'jL', 'jM', 'jH'], ['M', 'LH', 'jM', 'jH'], ['LH', 'jL', 'jM', 'jH']);
    for (const k of ['H', 'M', 'L']) for (const f of fuOf(k)) if (!M[f].special) cand.HARD.push(['L', 'M', 'H', f].slice(0, ['L', 'M', 'H'].indexOf(k) + 1).concat([f]));
    if (has('ult')) cand.SOUL.push(['L', 'L', 'L', 'M', 'H', 'ult'], ['L', 'M', 'H', 'ult'], ['ult']);   // last: grab ultimates (Goro) start their own combo
    const res = [], used = new Set();
    for (const tier of ['BASICS', 'EASY', 'MEDIUM', 'HARD', 'SOUL']) {
      let got = null;
      for (const seq of cand[tier]) {
        const key = seq.join(','); if (used.has(key)) continue;
        const r = await test(id, seq);
        if (r.ok) { got = { tier, seq, dmg: r.dmg, hits: r.hits }; used.add(key); break; }
      }
      if (got) res.push(got);
      console.log(id, tier, got ? got.seq.join(' ') + ` (${got.dmg} dmg, ${got.hits} hits)` : 'NONE');
    }
    out[id] = res;
  }
  fs.writeFileSync(outFile, '// generated by tests/gen_trials.js (bot-verified) — COMBO TRIALS per fighter\nconst COMBO_TRIALS = ' + JSON.stringify(out) + ';\n');
  console.log('errors', errors.filter(e => !/Failed to load resource/.test(e)).slice(0, 5));
  await browser.close();
})();
